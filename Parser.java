// Parser.java - recursive-descent parser; stops at the first syntax error

import java.util.List;

public class Parser {
     private List<Token> tokens;    // all tokens from the lexer
    private int currentIndex;      // position in the list
    private Token currentToken;    // token we are looking at right now
 
    public Parser(List<Token> tokens) {
        this.tokens = tokens;
        this.currentIndex = 0;
        this.currentToken = tokens.get(0);
    }
 
    // <program> -> <keyword> <ident> ( <keyword> <ident> ) { <declares> <assign> }
    public void parseProgram() {
        parseKeyword();
        parseIdent();
        match(TokenType.LEFT_PAREN, "Expected '(' after the function name");
        parseKeyword();
        parseIdent();
        match(TokenType.RIGHT_PAREN, "Expected ')' after the parameter");
        match(TokenType.LEFT_BRACE, "Expected '{' after ')'");
        parseDeclares();
        parseAssign();
        match(TokenType.RIGHT_BRACE, "Expected '}' at the end of the program");
        match(TokenType.END_OF_FILE, "Expected end of file after '}'");
    }
 
    // <declares> -> <keyword> <ident> ; | <keyword> <ident> ; <declares>
    private void parseDeclares() {
        parseKeyword();
        parseIdent();
        match(TokenType.SEMICOLON, "Expected ';' after declaration");
 
        // another declaration follows if the next token is "float"
        if (currentToken.getTokenType() == TokenType.KEYWORD) {
            parseDeclares();
        }
    }
 
    // <assign> -> <ident> = <expr>
    private void parseAssign() {
        parseIdent();
        match(TokenType.ASSIGN, "Expected '=' in the assignment");
        parseExpr();
 
        // the sample programs end the assignment with a ';'
        if (currentToken.getTokenType() == TokenType.SEMICOLON) {
            advance();
        } else if (currentToken.getTokenType() != TokenType.RIGHT_BRACE) {
            syntaxError("Expected '*', '/' or ';' after the expression");
        }
    }
 
    // <expr> -> <ident> {*|/} <expr> | <ident>
    private void parseExpr() {
        parseIdent();
 
        if (currentToken.getTokenType() == TokenType.MULTIPLY
                || currentToken.getTokenType() == TokenType.DIVIDE) {
            advance();
            parseExpr();
        }
    }
 
    // <keyword> -> float
    private void parseKeyword() {
        match(TokenType.KEYWORD, "Expected the keyword 'float'");
    }
 
    // <ident> -> letters a-z (the lexer already built the whole word)
    private void parseIdent() {
        match(TokenType.IDENTIFIER, "Expected an identifier");
    }
 

 
    // Move to the next token
    private void advance() {
        if (currentIndex < tokens.size() - 1) {
            currentIndex++;
        }
        currentToken = tokens.get(currentIndex);
    }
 
    // If the current token is the type we expect move on, otherwise it is an error.
    private void match(TokenType expected, String message) {
        if (currentToken.getTokenType() == expected) {
            advance();
        } else {
            syntaxError(message);
        }
    }
 
    // Print the first syntax error and stop the program
    private void syntaxError(String message) {
        System.out.println("The Sample Program cannot be generated by the LearnCompiler BNF Grammar");
        if (currentToken.getTokenType() == TokenType.END_OF_FILE) {
            System.out.println("Syntax Error on line " + currentToken.getLineNumber()
                    + ": " + message + ", but reached the end of the file.");
        } else {
            System.out.println("Syntax Error on line " + currentToken.getLineNumber()
                    + ": " + message + ", but found '" + currentToken.getLexeme() + "'.");
        }
        System.exit(0);
    }
}
