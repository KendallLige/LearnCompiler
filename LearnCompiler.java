import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.List;

public class LearnCompiler {
    public static void main(String[] args) throws Exception {
        // make sure a file name was given
        if (args.length == 0) {
            System.out.println("Usage: java LearnCompiler <sample-file>");
            return;
        }

        String text = new String(Files.readAllBytes(Paths.get(args[0])));

        Lexer lexer = new Lexer(text);
        List<Token> tokens = lexer.tokenize();

        // display the lexemes and tokens as a table
        System.out.println("Lexemes and Tokens");
        System.out.println("------------------------------------");
        System.out.printf("%-12s %-14s %s%n", "Lexeme", "Token", "Line");
        System.out.println("------------------------------------");

        for (Token t : tokens) {
            System.out.printf("%-12s %-14s %d%n",
                    t.getLexeme(), t.getTokenType(), t.getLineNumber());
        }

        System.out.println("------------------------------------");
        System.out.println();

        // check the syntax; the parser stops at the first error
        Parser parser = new Parser(tokens);
        parser.parseProgram();

        System.out.println("The Sample Program is generated by the BNF grammar");
    }
}
